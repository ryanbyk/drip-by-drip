const byId = new Map(BOOKS.map((book) => [book.id, book]));

export function getBook(id: string): Book | undefined {
  return byId.get(id);
}

export function chapterCount(bookId: string): number {
  return getBook(bookId)?.verses.length ?? 0;
}

export function verseCount(bookId: string, chapter: number): number {
  const book = getBook(bookId);
  if (!book || chapter < 1 || chapter > book.verses.length) return 0;
  return book.verses[chapter - 1] ?? 0;
}

export function totalVerses(bookId: string): number {
  return getBook(bookId)?.verses.reduce((sum, count) => sum + count, 0) ?? 0;
}

